class Solution {
    Node reverseList(Node head) {
        // code here
        Node temp=head;
        Node next=head;
        Node prev=null;
        while(next!=null){
            next=next.next;
            // change
            temp.next=prev;
            prev=temp;
            temp=next;
        }
        return prev;
    }
}

